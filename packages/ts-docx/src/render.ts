import MarkdownIt from "markdown-it";
import {
  Document,
  Packer,
  PageOrientation,
  convertMillimetersToTwip,
} from "docx";
import { blockChildren } from "./blocks.js";

export interface RenderMarkdownToDocxOptions {
  title?: string;
  /**
   * Язык документа — тег BCP-47, любая локаль из `SUPPORTED_LOCALES` `@ai37/agent-sdk` (`ru`, `en`,
   * `es`, `de`, `fr`, `pt`) или тег с регионом (`es-MX`, `ru-RU`). Задаёт язык текста по умолчанию
   * (`w:lang`: Word по нему проверяет орфографию и расставляет переносы) и описание в свойствах
   * файла. Не задан — язык не проставляется, описание русское, как раньше.
   */
  locale?: string;
}

/** Регион, который Word берёт для языка без региона: `es` — европейский, `pt` — бразильский. */
const WORD_LANGUAGE_REGION: Readonly<Record<string, string>> = {
  ru: "ru-RU",
  en: "en-US",
  es: "es-ES",
  de: "de-DE",
  fr: "fr-FR",
  pt: "pt-BR",
};

const DESCRIPTION: Readonly<Record<string, string>> = {
  ru: "Документ сформирован локальным детерминированным рендерером AI37",
  en: "Generated by the AI37 local deterministic renderer",
  es: "Documento generado por el renderizador determinista local de AI37",
  de: "Vom lokalen deterministischen AI37-Renderer erstelltes Dokument",
  fr: "Document généré par le moteur de rendu déterministe local d’AI37",
  pt: "Documento gerado pelo renderizador determinístico local da AI37",
};

const LOCALE_TAG = /^[a-z]{2,3}(-[a-z0-9]{1,8})*$/i;

/** Язык `w:lang`: тег с регионом — как есть, язык без региона — с регионом по умолчанию. */
function wordLanguage(locale: string): string | undefined {
  if (!LOCALE_TAG.test(locale)) return undefined;
  const language = locale.split("-")[0]!.toLowerCase();
  return locale.includes("-") ? locale : (WORD_LANGUAGE_REGION[language] ?? language);
}

/** Описание файла: язык без региона, иначе английский; без локали — русский. */
function description(locale: string | undefined): string {
  if (locale === undefined) return DESCRIPTION.ru!;
  return DESCRIPTION[locale.split("-")[0]!.toLowerCase()] ?? DESCRIPTION.en!;
}

const markdown = new MarkdownIt({
  html: false,
  linkify: false,
  typographer: false,
});

/** Рендерит markdown в DOCX полностью локально, без сети и внешнего состояния. */
export async function renderMarkdownToDocx(
  source: string,
  options: RenderMarkdownToDocxOptions = {},
): Promise<Buffer> {
  const language = options.locale ? wordLanguage(options.locale) : undefined;
  const document = new Document({
    creator: "AI37",
    title: options.title,
    description: description(options.locale),
    ...(language
      ? { styles: { default: { document: { run: { language: { value: language } } } } } }
      : {}),
    numbering: {
      config: [
        {
          reference: "ai37-numbering",
          levels: Array.from({ length: 9 }, (_, level) => ({
            level,
            format: "decimal",
            text: `%${level + 1}.`,
            alignment: "start",
            style: {
              paragraph: { indent: { left: 720 * (level + 1), hanging: 360 } },
            },
          })),
        },
      ],
    },
    sections: [
      {
        properties: {
          page: {
            size: { orientation: PageOrientation.PORTRAIT },
            margin: {
              top: convertMillimetersToTwip(20),
              right: convertMillimetersToTwip(15),
              bottom: convertMillimetersToTwip(20),
              left: convertMillimetersToTwip(30),
            },
          },
        },
        children: blockChildren(markdown.parse(source, {})),
      },
    ],
  });
  return Packer.toBuffer(document);
}
